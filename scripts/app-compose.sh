#!/bin/sh
# Write the Compose override for the extra installed layouts in <base>/sites/apps.
# Usage: sh scripts/app-compose.sh <base> [<apps folder>]
# The profiles are read from <apps folder> (default <base>/sites/apps). The build context
# is ${DAYFRAME_APPS_CONTEXT:-./sites/apps}/<id>, so update-remote.sh can build the layouts
# from sites/.incoming before they move into place.
# The first installed layout stays the `website` service; each extra layout gets its own
# hardened `app-<id>` service, socket volume and settings scope. The override is
# written to <base>/sites/compose.apps.yaml, or removed when there are no extra layouts.
# Prints the DAYFRAME_APPS value: "<id>=<scope> <id>=<scope> ...".
# Only validated profile fields reach the file, so it holds nothing but this template.
. "$(dirname "$0")/app-profile.sh"
set -eu
base=${1:?Usage: app-compose.sh <base>}
sites="$base/sites"
apps=${2:-$sites/apps}
output="$sites/compose.apps.yaml"
test ! -L "$sites"
test ! -L "$output"
value=""
services=""
mounts=""
needs=""
volumes=""
if test -e "$apps" || test -L "$apps"; then
    test ! -L "$apps"
    test -d "$apps"
    if test -n "$(ls -A "$apps")"; then
        test ! -L "$apps/.dayframe-apps-managed"
        test "$(cat "$apps/.dayframe-apps-managed")" = dayframe-apps-source-v1
    fi
    for dir in "$apps"/*; do
        test -e "$dir" || continue
        test ! -L "$dir"
        test -d "$dir"
        name=$(basename "$dir")
        profile="$dir/.install-profile"
        test ! -L "$dir/.dayframe-layout-managed"
        test "$(cat "$dir/.dayframe-layout-managed")" = dayframe-layout-source-v1
        read_profile "$profile" || { echo "The profile of the $name layout is not valid" >&2; exit 1; }
        test "$app_id" = "$name"
        value="${value:+$value }$app_id=$app_scope"
        services="$services
  app-$app_id:
    build:
      context: \"\${DAYFRAME_APPS_CONTEXT:-./sites/apps}/$app_id\"
      dockerfile: Dockerfile
    image: \"dayframe-app-$app_id:local\"
    restart: unless-stopped
    logging:
      driver: json-file
      options: {max-size: \"10m\", max-file: \"3\"}
    init: true
    user: \"10001:10001\"
    network_mode: \"$app_network\"
    read_only: true
    cap_drop: [ALL]
    security_opt: [no-new-privileges:true]
    mem_limit: \"${app_memory}m\"
    tmpfs:
      - /tmp:rw,noexec,nosuid,size=32m
    volumes:
      - \"app-$app_id-ipc:/run/dayframe-site\"
      - \"./data/layout-settings/$app_scope:/site-config:ro\"
      - \"./data/layout-state/$app_scope:/site-state\""
        mounts="$mounts
      - \"app-$app_id-ipc:/run/dayframe-apps/$app_id:ro\""
        needs="$needs
      - \"app-$app_id\""
        volumes="$volumes
  app-$app_id-ipc:"
    done
fi
if test -z "$value"; then
    rm -f "$output"
    exit 0
fi
temp=$(mktemp "$sites/.compose-apps.XXXXXX")
trap 'rm -f "$temp"' EXIT
{
    echo '# Generated by scripts/app-compose.sh from validated layout profiles. Do not edit.'
    echo '# Each extra installed layout runs in its own container with its own socket and settings.'
    echo 'services:'
    echo '  dayframe:'
    echo '    volumes:'"$mounts"
    echo '    depends_on:'"$needs"
    echo "$services" | sed '1d'
    echo 'volumes:'"$volumes"
} > "$temp"
chmod 644 "$temp"
mv "$temp" "$output"
trap - EXIT
printf '%s\n' "$value"
